// 区域类型
typedef struct {
    int16_t X ;
    int16_t Y ;
    uint16_t W ;
    uint16_t H ;
} Area_t  ;


// 锚点类型
typedef enum {
    Anchor_LT = 0 , // 左上
    Anchor_LM ,     // 左中
    Anchor_LB ,     // 左下

    Anchor_CT ,     // 中上
    Anchor_CM ,     // 中中
    Anchor_CB ,     // 中下

    Anchor_RT ,     // 右上
    Anchor_RM ,     // 右中
    Anchor_RB ,     // 右下
} Anchor_t ;

