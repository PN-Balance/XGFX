/**
 * @brief 初始化一个 1 ms 定时器并且运行
 * 
 */
void Tick_Port_Timer_Init( void )
{
    NVIC_SetPriority( SysTick_IRQn , UC_TICK_TIMER_UPDATA_IT_PRIOTY );
    NVIC_EnableIRQ( SysTick_IRQn );

    /* Configure the SysTick to have interrupt in 1ms time base */
    SysTick->LOAD  = (uint32_t)(( 72000000 / 1000 ) - 1UL);  /* set reload register */
    SysTick->VAL   = 0UL;                                       /* Load the SysTick Counter Value */
    SysTick->CTRL  = SysTick_CTRL_CLKSOURCE_Msk |
                     SysTick_CTRL_TICKINT_Msk |
                SysTick_CTRL_ENABLE_Msk;                   /* Enable the Systick Timer */
    

}


/**
 * @brief 滴答计数中断句柄
 * 
 */
/**
  * @brief This function handles System tick timer.
  */
void SysTick_Handler( void )
{
    volatile uint32_t dummy = SysTick->VAL; // 读取可能帮助清除
    
    Tick_CallBack_1ms_Timer();
}

