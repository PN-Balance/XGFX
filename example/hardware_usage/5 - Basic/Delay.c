/**
 * @brief 秒 延时函数
 * 
 * @param s 
 * 
 */
void Delay_s( uint32_t s )
{
    while( s-- )
    {
        Delay_ms( 1000 );
    }
}

/**
 * @brief 毫秒 延时函数
 * 
 * @param ms 毫秒数
 * 
 */
void Delay_ms( uint32_t ms )
{
    while( ms-- )
    {
        Delay_us( 1000 );
    }
}



