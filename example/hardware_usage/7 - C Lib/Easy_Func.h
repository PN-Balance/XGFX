/* 循环加减 */
#define CICLE_ADD( X , RANGE )   X = ( X + 1 ) % ( RANGE ) 
#define CICLE_MINUS( X , RANGE )     X = ( X ? X - 1 : ( RANGE ) - 1 )

/* 有上限的加 */
#define END_ADD( X , Y ) X = ( X  + 1 ) >= Y ? X : X + 1 

/* 有下限的减 */
#define END_ZERO_SUB( X ) X = X > 0 ? X - 1 : 0 

/* 无符号整型数据向后四字节对齐 */
#define ALIGN_UP_4( x ) ( ( ( x ) + 3 ) & ~3 )

// 无符号整型数据向后N字节对齐 使用算术运算（N必须是2的幂次方）
#define ALIGN_UP_POW2(x, n) (((x) + (n) - 1) & ~((n) - 1))

// 无符号整型数据向后N字节对齐 通用方法，适用于任意N（不要求是2的幂次方）
#define ALIGN_UP(x, n) ((x) % (n) == 0 ? (x) : ((x) + (n) - (x) % (n)))

