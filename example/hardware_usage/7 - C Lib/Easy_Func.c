/**
 * @brief 计算指定长度的数据的CRC校验值
 * 
 * @param Data 
 * @param Length 
 * 
 * @return uint16_t 
 */
uint16_t CRC_Calculate( uint8_t Data[  ] , uint32_t Length )
{
    uint16_t CRC_Value = 0xFFFF ;

    while( Length-- ) 
    {
        CRC_Value = ( CRC_Value >> 8 ) ^ CRC_Table[ ( CRC_Value ^ *Data++ ) & 0xFF ]; //原理参考直接计算法
    }

    return CRC_Value ;
}

/**
 * @brief CRC计算器复位函数
 * @details 此函数用于将CRC计算器的临时值重置为初始值0xFFFF
 */
void CRC_Calculator_Reset( void )
{
    // 将CRC计算的临时值设置为初始值0xFFFF
    Temp_CRC_Value = 0xFFFF ;
}


/**
 * @brief CRC计算器输入函数
 * 
 * @param data 指向待计算CRC的数据块的指针
 * @param size 待计算CRC的数据块的大小
 * 
 */
void CRC_Calculator_Input( const uint8_t *data, uint32_t size )
{
    if( data == NULL ) return;

    for( uint32_t i = 0 ; i < size ; i++ ) //  遍历数据块计算CRC值
    {
        Temp_CRC_Value = ( Temp_CRC_Value >> 8 ) ^ CRC_Table[ ( Temp_CRC_Value ^ *data ) & 0xFF ]; //原理参考直接计算法
        data++;
    }
}

/**
 * @brief CRC计算器输出函数
 * 
 * 
 * @return uint16_t CRC计算结果
 */
uint16_t CRC_Calculator_Output( void )
{
    return Temp_CRC_Value ;
}


/**
 * @brief 计算从active角度到target角度的最短路径差值（有符号）
 * 
 * @param target      目标角度，单位为度（范围：[0,360)）
 * @param active      起始角度，单位为度（范围：[0,360)）
 * @return double     从active到target的变化量，范围：(-180, 180]
 *                    正值表示顺时针增加，负值表示逆时针减少
 * 
 * @note 示例：
 *       active=45, target=60  → 返回 +15  (顺时针转15度)
 *       active=60, target=45  → 返回 -15  (逆时针转15度)
 *       active=1,  target=359 → 返回 -2   (逆时针转2度，比顺时针转358度短)
 */
double Ang_360_Diff_Calculate(double target, double active) {
    double diff = fmod(target - active, 360.0);
    
    // 调整到 (-180, 180] 范围
    if (diff > 180.0) {
        diff -= 360.0;
    } else if (diff <= -180.0) {
        diff += 360.0;
    }
    
    // 处理浮点误差导致的 -0.0
    if (fabs(diff) < 1e-10) {
        diff = 0.0;
    }
    
    return diff;
}

