/**
 * @brief 计算从当前角度到目标角度的最短步数差值（有符号）
 * 
 * @param Current 
 * @param Limit 
 * @param Target 
 * 
 * @return int32_t 
 */
int32_t Counter_GetDelta(uint32_t Current, uint32_t Limit, uint32_t Target) {
    if (Current == Target) {
        return 0;
    }
    
    // 计算顺时针（增加）需要多少步
    uint32_t steps_clockwise;
    if (Target >= Current) {
        steps_clockwise = Target - Current;
    } else {
        steps_clockwise = Limit - Current + Target;
    }
    
    // 计算逆时针（减少）需要多少步
    uint32_t steps_counterclockwise;
    if (Current >= Target) {
        steps_counterclockwise = Current - Target;
    } else {
        steps_counterclockwise = Current + Limit - Target;
    }
    
    // 选择步数少的方向
    if (steps_clockwise <= steps_counterclockwise) {
        return (int32_t)steps_clockwise;
    } else {
        return -(int32_t)steps_counterclockwise;
    }
}
